import CucumberSwiftGherkin
import Foundation

/// The Swift Testing source for a target's feature files: one suite for all of them, serialized as
/// CucumberSwift runs one scenario at a time unless `CUCUMBER_PARALLEL_TESTING` says otherwise; in it a
/// suite per feature; in that a test per Scenario, and a parameterized test per Scenario Outline, with a
/// test case per example.
enum SwiftTestingSource {
    /// A parsed feature file and its path.
    struct Input {
        let path: String
        let file: FeatureFile
    }

    /// What a generated `GherkinScenario` holds besides its feature: a Scenario's, or an example's.
    private struct ScenarioParts {
        let title: String
        let tags: [String]
        let line: Int
        let column: Int
        let steps: [FeatureFile.Step]
    }

    /// The constants that the tests run, in the order of the tests.
    private struct Data {
        var source = ""
        var count = 0

        mutating func add(_ kind: String, _ value: String) -> String {
            count += 1
            let name = "cucumber\(kind)\(count)"
            source += "\nprivate let \(name) = \(value)\n"
            return name
        }
    }

    /// The last line of a suggested step definition, which fails the step until it is filled in.
    static let failure = "Issue.record(\"Step not implemented: replace this line with your test code\")"

    /// Names the generated code can't use for a suite or a test: they would hide what it refers to.
    static let reservedNames: Set<String> = [
        "CucumberFeatures", "CucumberSwiftTesting", "Testing", "Test", "Suite", "Self", "Type", "Protocol", "Any", "Sendable"
    ]

    /// Whether the test target defines the compilation condition `CUCUMBER_PARALLEL_TESTING`.
    private static let parallelTesting = """
        #if CUCUMBER_PARALLEL_TESTING
        private let cucumberParallelTesting = true
        #else
        private let cucumberParallelTesting = false
        #endif

        /// Names the test bundle these tests are in, which the JSON report names its feature files and its copy after.
        private final class CucumberFeaturesBundle {}


        """

    /// What a Swift file looks like when it writes a feature in the Swift DSL: a call of `Feature` or `#Feature`, or
    /// of a name such as `ES_Característica`, a localized type of the DSL, or its macro, which this can't tell from a
    /// localized step definition such as `ES_Dado("…")` or `#ES_Dado("…")`. A step definition only adds the test with no cases, which Swift Testing
    /// shows as skipped; a feature this missed would not run, which the runner reports when the suite ends.
    private static let dslFeaturePattern = try? NSRegularExpression(pattern: ##"(?<![\w#])#?(?:Feature|[A-Z][A-Z0-9]*(?:[_-][A-Z0-9]+)*_[^\s(){}\[\]"#.,:;]+)(?:\.init)?\s*\("##)

    /// Whether a Swift file's text writes a feature in the Swift DSL, by ``dslFeaturePattern``.
    static func writesDSLFeatures(_ text: String) -> Bool {
        dslFeaturePattern?.firstMatch(in: text, range: NSRange(text.startIndex..., in: text)) != nil
    }

    /// The tests, or with no feature files and no features written in the Swift DSL, a file with none.
    static func generate(_ inputs: [Input], dslFeatures: Bool = false) -> String {
        guard !inputs.isEmpty || dslFeatures else {
            return "// Generated by CucumberSwiftTestingPlugin. This target has no feature files and no features written in the Swift DSL.\n"
        }
        // Not serialized: the suite is, unless scenarios run in parallel, when each case is a whole scenario.
        let dslTest = !dslFeatures ? "" : "\n\n"
            + "    @Test(\"Swift DSL features\", arguments: await CucumberSwiftTesting.Cucumber.shared.dslCasesToRun(parallelCompiled: cucumberParallelTesting, "
            + "testBundle: CucumberSwiftTesting.cucumberTestBundle(of: CucumberFeaturesBundle.self)))\n"
            + "    func swiftDSL(_ testCase: CucumberSwiftTesting.ScenarioCase) async throws { try await CucumberSwiftTesting.Cucumber.shared.run(testCase) }"
        var source = """
        // Generated by CucumberSwiftTestingPlugin from this target's feature files. Do not edit.
        //
        // One suite holds every feature in the target, and the features its Swift files write in the Swift
        // DSL, if they write any, in one test. The suite is serialized, because CucumberSwift runs one
        // scenario at a time, and step definitions often share state, unless parallel testing is on: the
        // environment variable CUCUMBER_PARALLEL_TESTING says so when Swift Testing discovers the tests,
        // or else the compilation condition of that name. A failed expectation is reported in the feature
        // file. Each test takes two lines, and the scenarios' contents come after all the
        // tests, so that editing a feature file moves no test: Xcode lists the tests from a copy of this
        // file that it doesn't always update, and matches results to them by line. These comments are here
        // rather than on the suite, where Swift Testing would show them with each failure.

        import CucumberSwiftTesting
        import Testing

        @MainActor
        @Suite("Features", CucumberSwiftTesting.cucumberScenarioOrder(compiled: cucumberParallelTesting), .reportedInFeatureFiles, .observedByCucumber)
        struct CucumberFeatures {
            @Test("Feature files are valid Gherkin")
            func gherkin() { cucumberGherkinProblems() }\(dslTest)

        """
        var data = Data()
        var suiteNames = Set<String>()
        for input in inputs {
            for feature in input.file.features where !feature.scenarios.isEmpty {
                let name = uniqueName(FeatureFile.typeName(for: feature.title), fallback: "Feature", in: &suiteNames)
                source += "\n" + suite(for: feature, named: name, path: input.path, data: &data)
            }
        }
        let problems = inputs.flatMap { input in input.file.problems.map { (path: input.path, problem: $0) } }
        return source + "}\n\n" + "// MARK: - What the tests run\n\n" + parallelTesting + gherkinProblems(problems) + data.source
    }

    /// Records each problem in the feature files, as CucumberSwift's `testGherkin()` does.
    private static func gherkinProblems(_ problems: [(path: String, problem: String)]) -> String {
        let issues = problems.map { problem in
            let fileID = literal("Features/" + URL(fileURLWithPath: problem.path).lastPathComponent)
            let location = "SourceLocation(fileID: \(fileID), filePath: \(literal(problem.path)), line: 1, column: 1)"
            return "    Issue.record(\(literal(problem.problem)), sourceLocation: \(location))\n"
        }
        return "private func cucumberGherkinProblems() {\n" + issues.joined() + "}\n"
    }

    private static func suite(for feature: FeatureFile.Feature, named name: String, path: String, data: inout Data) -> String {
        var testNames = Set<String>()
        let tests = feature.scenarios.map { scenario in
            let testName = uniqueName(FeatureFile.typeName(for: scenario.title), fallback: "Scenario", in: &testNames)
            return test(for: scenario, named: testName, in: feature, path: path, data: &data)
        }
        return """
            @MainActor
            @Suite\(displayName(feature.title, adding: featureTrait(feature, path: path)))
            struct \(name) {
        \(tests.joined(separator: "\n\n"))
            }

        """
    }

    /// The test, in two lines, and its scenario or examples, which are added to `data` as a constant.
    private static func test(
        for scenario: FeatureFile.Scenario,
        named name: String,
        in feature: FeatureFile.Feature,
        path: String,
        data: inout Data
    ) -> String {
        let displayName = scenario.title.isEmpty ? "" : literal(scenario.title) + ", "
        guard let examples = scenario.examples else {
            let parts = ScenarioParts(
                title: scenario.title,
                tags: scenario.tags,
                line: scenario.line,
                column: scenario.column,
                steps: scenario.steps)
            let constant = data.add("Scenario", gherkinScenario(parts, of: feature, path: path, indent: 0))
            return """
                    @Test(\(displayName).serialized, .enabled { await CucumberSwiftTesting.Cucumber.shared.shouldRun(\(constant)) },
                          arguments: await CucumberSwiftTesting.Cucumber.shared.casesToRun(\(constant)))
                    func \(name)(_ testCase: CucumberSwiftTesting.ScenarioCase) async throws { try await CucumberSwiftTesting.Cucumber.shared.run(testCase) }
            """
        }
        let arguments = examples.map { example in
            let parts = ScenarioParts(title: example.title, tags: example.tags, line: example.line, column: example.column, steps: example.steps)
            return "    CucumberSwiftTesting.GherkinExample(\n" + gherkinScenario(parts, of: feature, path: path, indent: 8) + ")"
        }
        let constant = data.add("Examples", "[\n" + arguments.joined(separator: ",\n") + "\n]")
        return """
                @Test(\(displayName).serialized, arguments: await CucumberSwiftTesting.Cucumber.shared.casesToRun(\(constant)))
                func \(name)(_ testCase: CucumberSwiftTesting.ScenarioCase) async throws { try await CucumberSwiftTesting.Cucumber.shared.run(testCase) }
        """
    }

    private static func gherkinScenario(_ parts: ScenarioParts, of feature: FeatureFile.Feature, path: String, indent: Int) -> String {
        let pad = String(repeating: " ", count: indent)
        let stepLines = parts.steps.map { pad + "        " + gherkinStep($0, indent: indent + 8) }
        return pad + "CucumberSwiftTesting.GherkinScenario(\n"
            + pad + "    featureTitle: \(literal(feature.title)),\n"
            + pad + "    featureTags: \(array(feature.tags)),\n"
            + pad + "    featureDescription: \(literal(feature.description)),\n"
            + pad + "    featureLine: \(feature.line),\n"
            + pad + "    title: \(literal(parts.title)),\n"
            + pad + "    tags: \(array(parts.tags)),\n"
            + pad + "    file: \(literal(path)),\n"
            + pad + "    testBundle: CucumberSwiftTesting.cucumberTestBundle(of: CucumberFeaturesBundle.self),\n"
            + pad + "    line: \(parts.line),\n"
            + pad + "    column: \(parts.column),\n"
            + pad + "    steps: [\n"
            + stepLines.joined(separator: ",\n") + (stepLines.isEmpty ? "" : "\n")
            + pad + "    ])"
    }

    private static func gherkinStep(_ step: FeatureFile.Step, indent: Int) -> String {
        let pad = String(repeating: " ", count: indent)
        let keywords = FeatureFile.Keyword.allCases.filter(step.keywords.contains).map { ".\($0.rawValue)" }
        var arguments = [
            "keyword: [\(keywords.joined(separator: ", "))]",
            "keywordName: \(literal(step.keywordName))",
            "keywordText: \(literal(step.keywordText))",
            "text: \(literal(step.text))",
            "line: \(step.line)",
            "column: \(step.column)"
        ]
        if let docString = step.docString {
            let contentType = docString.contentType.map(literal) ?? "nil"
            arguments.append("docString: CucumberSwiftTesting.DocString(literal: \(literal(docString.literal)), "
                             + "rawLiteral: \(literal(docString.rawLiteral)), contentType: \(contentType))")
        }
        if let dataTable = step.dataTable {
            arguments.append("dataTable: [\(dataTable.map(array).joined(separator: ", "))]")
        }
        arguments.append("suggestion: \(literal(step.suggestedStepDefinition(failure: failure)))")
        // For `Cucumber.generateRegexLiterals`, which the runner reads when a step is undefined.
        arguments.append("regexLiteralSuggestion: \(literal(step.suggestedRegexLiteralStepDefinition(failure: failure, bareSlash: false)))")
        arguments.append("bareSlashRegexLiteralSuggestion: \(literal(step.suggestedRegexLiteralStepDefinition(failure: failure, bareSlash: true)))")
        // For `Cucumber.generateMacros`.
        arguments.append("macroSuggestion: \(literal(step.suggestedStepDefinition(failure: failure, macro: true)))")
        arguments.append("regexLiteralMacroSuggestion: "
                         + literal(step.suggestedRegexLiteralStepDefinition(failure: failure, bareSlash: false, macro: true)))
        arguments.append("bareSlashRegexLiteralMacroSuggestion: "
                         + literal(step.suggestedRegexLiteralStepDefinition(failure: failure, bareSlash: true, macro: true)))
        return "CucumberSwiftTesting.GherkinStep(\n"
            + arguments.map { pad + "    " + $0 }.joined(separator: ",\n")
            + ")"
    }

    /// The traits that tell the runner where the feature ends, and whether its scenarios run one at a time
    /// while features run at the same time.
    private static func featureTrait(_ feature: FeatureFile.Feature, path: String) -> String {
        ".cucumberFeature(file: \(literal(path)), title: \(literal(feature.title)), line: \(feature.line)), "
            + "CucumberSwiftTesting.cucumberFeatureOrder(compiled: cucumberParallelTesting)"
    }

    /// `("title", trait)` for a suite with a title, `(trait)` for one without.
    private static func displayName(_ title: String, adding trait: String) -> String {
        "(" + (title.isEmpty ? "" : literal(title) + ", ") + trait + ")"
    }

    /// `name`, or `fallback` when it is empty or reserved, with a number added if it is already used.
    static func uniqueName(_ name: String, fallback: String, in used: inout Set<String>) -> String {
        let base = name.isEmpty || reservedNames.contains(name) ? fallback : name
        var candidate = base
        var count = 2
        while used.contains(candidate) {
            candidate = "\(base)_\(count)"
            count += 1
        }
        used.insert(candidate)
        return candidate
    }

    /// `text` as a Swift string literal.
    static func literal(_ text: String) -> String {
        var escaped = ""
        for scalar in text.unicodeScalars {
            switch scalar {
                case "\\": escaped += "\\\\"
                case "\"": escaped += "\\\""
                case "\n": escaped += "\\n"
                case "\r": escaped += "\\r"
                case "\t": escaped += "\\t"
                case _ where scalar.value < 0x20 || scalar.value == 0x7F:
                    escaped += "\\u{\(String(scalar.value, radix: 16))}"
                default: escaped.unicodeScalars.append(scalar)
            }
        }
        return "\"\(escaped)\""
    }

    private static func array(_ items: [String]) -> String {
        "[" + items.map(literal).joined(separator: ", ") + "]"
    }
}
