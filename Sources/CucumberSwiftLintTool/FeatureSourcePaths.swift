import Foundation

/// The Swift file the CucumberSwiftLint plugin adds to the target: a class with the path of each of its feature
/// files in the project. CucumberSwift's XCTest runner reads the features from their copies in the test
/// bundle, and reports each issue about one at the project's file instead, as the Swift Testing runner does.
/// The runner finds the class by the start of its Objective-C name, so keep `classNamePrefix` the same as
/// CucumberSwift's `FeatureSourceFiles.recordedPathsClassNamePrefix`.
enum FeatureSourcePaths {
    static let classNamePrefix = "CucumberSwiftFeatureSourcePaths_"

    /// The class's name for `target`. SwiftPM links all of a package's test targets into one test bundle, so
    /// each target's class needs a name of its own.
    static func className(target: String) -> String {
        classNamePrefix + String(target.unicodeScalars.map { scalar -> Character in
            scalar.isASCII && (CharacterSet.alphanumerics.contains(scalar) || scalar == "_") ? Character(scalar) : "_"
        })
    }

    /// The Swift file for `target`, with `features`, its feature files' paths. It builds in Swift 5 and Swift 6
    /// language modes.
    static func source(target: String, features: [String]) -> String {
        let className = className(target: target)
        let paths = features.map { "        \(literal($0))," }.joined(separator: "\n")
        return """
        // Generated by the CucumberSwiftLint plugin. CucumberSwift's XCTest runner reports issues at these
        // feature files, rather than at their copies in the test bundle.
        import Foundation

        @objc(\(className))
        final class \(className): NSObject {
            @objc static let target = \(literal(target))
            @objc static let paths: [String] = [
        \(paths)
            ]
        }

        """
    }

    /// `string` as a Swift string literal.
    static func literal(_ string: String) -> String {
        var escaped = ""
        for scalar in string.unicodeScalars {
            switch scalar {
                case "\\": escaped += "\\\\"
                case "\"": escaped += "\\\""
                case "\n": escaped += "\\n"
                case "\r": escaped += "\\r"
                case "\t": escaped += "\\t"
                case _ where scalar.value < 0x20 || scalar.value == 0x7F:
                    escaped += "\\u{\(String(scalar.value, radix: 16))}"
                default: escaped.unicodeScalars.append(scalar)
            }
        }
        return "\"\(escaped)\""
    }

    /// Writes the Swift file for `target` and `features` to `path`.
    static func write(target: String, features: [String], to path: String) throws {
        try Data(source(target: target, features: features).utf8).write(to: URL(fileURLWithPath: path), options: .atomic)
    }
}
