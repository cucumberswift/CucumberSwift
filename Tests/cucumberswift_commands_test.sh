#!/bin/bash
# Runs each command of the cucumberswift tool that the plugins run, as a Bazel project runs it
# (bazel/cucumberswift.bzl): lint, generate, fix-feature-files and convert-to-gherkin-macros.
# $1 is the tool.

set -euo pipefail

cli="$(cd "$(dirname "$1")" && pwd)/$(basename "$1")"
work="$(mktemp -d "${TEST_TMPDIR:-${TMPDIR:-/tmp}}/commands_test.XXXXXX")"
trap 'rm -rf "$work"' EXIT
cd "$work"

fail() { echo "FAIL: $*" >&2; exit 1; }

printf 'Feature: Greeting\n  Scenario: Say hello\n    Giben a greeting\n    Whn it is said\n    Then hello is heard\n' > Greeting.feature
printf 'import CucumberSwiftTesting\n' > Steps.swift

# lint: a warning for each misspelt keyword, on the line it is on, and a status of 0 so a warning does not fail the build.
"$cli" lint --stamp stamp --features Greeting.feature --step-definitions Steps.swift > lint.out || fail "lint failed on warnings"
grep -q "Greeting.feature:3:5: warning: 'Giben' is not a Gherkin keyword. Did you mean 'Given'?" lint.out || fail "lint did not warn about Giben: $(cat lint.out)"
grep -q "Greeting.feature:4:5: warning: 'Whn' is not a Gherkin keyword. Did you mean 'When'?" lint.out || fail "lint did not warn about Whn: $(cat lint.out)"
[[ "$(cat stamp)" == "2" ]] || fail "lint wrote the stamp '$(cat stamp)', not 2"

# generate: a Swift Testing test for the scenario.
"$cli" generate --output Generated.swift Greeting.feature --swift Steps.swift || fail "generate failed"
grep -q "Generated by CucumberSwiftTestingPlugin" Generated.swift || fail "generate wrote no header"
grep -q "Say hello" Generated.swift || fail "generate wrote no test for the scenario"
"$cli" generate --output Missing.swift Missing.feature && fail "generate accepted a feature file that does not exist"
[[ ! -e Missing.swift ]] || fail "generate wrote a file for a feature file that does not exist"

# fix-feature-files: applies the suggestions and prints each line it changed.
"$cli" fix-feature-files Greeting.feature > fix.out || fail "fix-feature-files failed"
grep -q "Fixed 2 lines in 1 of 1 feature file." fix.out || fail "fix-feature-files said: $(cat fix.out)"
grep -q "^    Given a greeting$" Greeting.feature || fail "Giben was not fixed"
grep -q "^    When it is said$" Greeting.feature || fail "Whn was not fixed"
"$cli" lint --stamp stamp --features Greeting.feature --step-definitions Steps.swift > lint.out
[[ "$(cat stamp)" == "0" && ! -s lint.out ]] || fail "lint still warned after the fix: $(cat lint.out)"

# convert-to-gherkin-macros: Bazel builds the tool without swift-syntax, so it changes nothing, exits 2 and says what to turn on.
status=0
"$cli" convert-to-gherkin-macros --root "$work" Steps.swift > convert.out 2>&1 || status=$?
[[ "$status" == 2 ]] || fail "convert-to-gherkin-macros exited $status, not 2: $(cat convert.out)"
grep -q "Macros" convert.out || fail "convert-to-gherkin-macros did not say what to turn on: $(cat convert.out)"

# An unknown command and no command: the usage and a status of 2.
status=0
"$cli" unknown > /dev/null 2>&1 || status=$?
[[ "$status" == 2 ]] || fail "an unknown command exited $status, not 2"

echo "PASS"
